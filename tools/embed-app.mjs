// Copies the single-file game build into the Expo app as a JS module (no file-system access needed at runtime).
import { readFileSync, writeFileSync } from 'node:fs';

const html = readFileSync('dist-app/index.html', 'utf8');
writeFileSync('mobile/game/html.js', `// Generated by \`npm run app:sync\` from the web build. Do not edit.\nexport default ${JSON.stringify(html)};\n`);
console.log(`embedded ${(html.length / 1024).toFixed(0)} KB into mobile/game/html.js`);
